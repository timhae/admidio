<?php
/**
 ***********************************************************************************************
 * Generates the Admidio configuration file adm_my_files/config.php from the options
 * of the NixOS services.admidio module.
 *
 * It is run by admidio-provision.service so the database password is read from
 * the systemd credentials directory at runtime and never becomes part of the
 * Nix store.
 *
 * Usage:
 *   php config-gen.php --out=FILE --db-type=TYPE --table-prefix=PREFIX --db-host=HOST
 *     [--db-port=PORT] --db-name=NAME --db-user=USER [--password-file=FILE]
 *     --root-url=URL --timezone=ZONE --login-for-update=0|1
 *     --password-hash-algorithm=ALGORITHM --debug=0|1
 *
 * @copyright The Admidio Team
 * @see https://www.admidio.org/
 * @license https://www.gnu.org/licenses/gpl-2.0.html GNU General Public License v2.0 only
 ***********************************************************************************************
 */

$longopts = array(
    'out:',
    'db-type:',
    'table-prefix:',
    'db-host:',
    'db-port:',
    'db-name:',
    'db-user:',
    'password-file:',
    'root-url:',
    'timezone:',
    'login-for-update:',
    'password-hash-algorithm:',
    'debug:'
);
$options = getopt('', $longopts);
if ($options === false) {
    fwrite(STDERR, "config-gen.php: cannot parse the arguments\n");
    exit(1);
}

$required = array(
    'out', 'db-type', 'table-prefix', 'db-host', 'db-name', 'db-user',
    'root-url', 'timezone', 'login-for-update', 'password-hash-algorithm', 'debug'
);
foreach ($required as $name) {
    if (!isset($options[$name]) || $options[$name] === '') {
        fwrite(STDERR, "config-gen.php: missing required option --$name\n");
        exit(1);
    }
}

// an empty --db-port keeps the default port of the database system
$port = (isset($options['db-port']) && $options['db-port'] !== '')
    ? (int)$options['db-port']
    : null;

$password = '';
if (isset($options['password-file']) && $options['password-file'] !== '') {
    $raw = file_get_contents($options['password-file']);
    if ($raw === false) {
        fwrite(STDERR, "config-gen.php: cannot read the password file\n");
        exit(1);
    }
    // a trailing newline is the line ending of the file, not part of the password
    $password = rtrim($raw, "\r\n");
}

$render = static function ($value): string {
    return var_export($value, true);
};

$content = '<?php
/**
 ***********************************************************************************************
 * Configuration file of Admidio
 *
 * This file was generated by the NixOS services.admidio module from the
 * services.admidio.* options. It is regenerated whenever the
 * admidio-provision service runs, so manual changes are lost.
 *
 * @copyright The Admidio Team
 * @see https://www.admidio.org/
 * @license https://www.gnu.org/licenses/gpl-2.0.html GNU General Public License v2.0 only
 ***********************************************************************************************
 */

// Select your database system between \'mariadb\', \'mysql\' or \'pgsql\'
$gDbType = ' . $render($options['db-type']) . ';

// Table prefix for Admidio-Tables in database
// Example: \'adm\'
$g_tbl_praefix = ' . $render($options['table-prefix']) . ';

// Access to the database
$g_adm_srv  = ' . $render($options['db-host']) . '; // Server
$g_adm_port = ' . $render($port) . '; // Port
$g_adm_db   = ' . $render($options['db-name']) . '; // Database
$g_adm_usr  = ' . $render($options['db-user']) . '; // User
$g_adm_pw   = ' . $render($password) . '; // Password

// URL to this Admidio installation
// Example: \'https://www.admidio.org/example\'
$g_root_path = ' . $render($options['root-url']) . ';

// The name of the timezone in which your organization is located.
// This must be one of the strings that are defined here https://www.php.net/manual/en/timezones.php
// Example: \'Europe/Berlin\'
$gTimezone = ' . $render($options['timezone']) . ';

// If this flag is set = 1 then you must enter your loginname and password
// for an update of the Admidio database to a new version of Admidio.
// For a more comfortable and easy update you can set this preference = 0.
$gLoginForUpdate = ' . (int)$options['login-for-update'] . ';

// Set the preferred password hashing algorithm.
// Possible values are: \'DEFAULT\', \'ARGON2ID\', \'ARGON2I\', \'BCRYPT\', \'SHA512\'
$gPasswordHashAlgorithm = ' . $render($options['password-hash-algorithm']) . ';

// If this flag is set = true, Admidio shows PHP errors and the SQL statements.
$gDebug = ' . (filter_var($options['debug'], FILTER_VALIDATE_BOOLEAN) ? 'true' : 'false') . ';
';

if (file_put_contents($options['out'], $content) === false) {
    fwrite(STDERR, "config-gen.php: cannot write the configuration file\n");
    exit(1);
}
if (chmod($options['out'], 0600) === false) {
    fwrite(STDERR, "config-gen.php: cannot set the permissions of the configuration file\n");
    exit(1);
}
exit(0);
